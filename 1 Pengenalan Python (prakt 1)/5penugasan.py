jumlah = 10
jumlah += 5
print(f"jumlahnya {jumlah}")
print("------------------------")
#output: jumlahnya 15

jumlah = 10
jumlah -= 5
print(f"jumlahnya {jumlah}")
print("------------------------")
#output: jumlahnya 5

jumlah = 10
jumlah *= 5
print(f"jumlahnya {jumlah}")
print("------------------------")
#output: jumlahnya 50

jumlah = 10
jumlah /= 5
print(f"jumlahnya {jumlah}")
print("------------------------")
#output: jumlahnya 2